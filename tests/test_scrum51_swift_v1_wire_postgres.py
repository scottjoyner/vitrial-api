"""Real Swift JSONEncoder Item V1 push/pull against disposable PostgreSQL 17.

Opt-in only. The fixture is generated by a synthetic Swift XCTest on x1-370,
not historical quotation data, real customer identities or a supplier catalog.
"""
import base64
import copy
import hashlib
import json
import os
from pathlib import Path
from uuid import uuid4

import pytest
from httpx import ASGITransport, AsyncClient
from sqlalchemy import delete, select

from app.db import SessionFactory
from app.main import app
from app.models import (
    AuthSession, CanonicalCustomer, CanonicalItem, CanonicalProject,
    CanonicalProjectSector, Membership, Organization, SyncChangeLog,
    SyncEntity, SyncMutation, User,
)
from app.idempotency import SyncMutationFingerprint
from app.settings import settings

FIXTURE_ENV = "VITRIAL_SYNTHETIC_SWIFT_ITEM_V1_BATCH_FILE"
pytestmark = pytest.mark.skipif(
    os.getenv("POSTGRES_INTEGRATION") != "1" or not os.getenv(FIXTURE_ENV),
    reason="requires disposable PostgreSQL and an explicitly supplied synthetic Swift wire",
)
ADMIN_KEY = "synthetic-swift-v1-interoperability-only"


async def cleanup(org: str):
    async with SessionFactory() as db:
        users = (await db.scalars(
            select(Membership.user_id).where(Membership.organization_id == org)
        )).all()
        for model in (
            SyncChangeLog, SyncEntity, SyncMutation, SyncMutationFingerprint,
            CanonicalItem, CanonicalProjectSector, CanonicalProject,
            CanonicalCustomer, AuthSession, Membership,
        ):
            await db.execute(delete(model).where(model.organization_id == org))
        await db.flush()
        if users:
            await db.execute(delete(User).where(User.id.in_(users)))
        await db.execute(delete(Organization).where(Organization.id == org))
        await db.commit()


@pytest.mark.asyncio
async def test_swift_v1_item_batch_http_push_and_pull_with_real_postgres(monkeypatch):
    path = Path(os.environ[FIXTURE_ENV])
    assert path.is_file() and not path.is_symlink()
    wire = json.loads(path.read_bytes())
    assert wire["deviceID"] == "synthetic-offline-device"
    assert len(wire["records"]) == 1
    rec = wire["records"][0]
    assert rec["entityType"] == "item" and rec["entityID"] == "synthetic-item"
    assert rec["clientMutationID"] == rec["id"]
    assert rec.get("serverRevision") is None and rec.get("baseServerRevision") is None
    payload = json.loads(base64.b64decode(rec["payload"], validate=True))
    assert payload["id"] == "synthetic-item"
    assert payload["projectID"] == "synthetic-project"
    assert payload["projectSectorID"] == "synthetic-sector"
    assert payload["jobItemDraft"]["templateReviewStatus"] == "pending_customer_review"
    assert payload["jobItemDraft"]["opening"] == {
        "kind": "l_shape", "heightCm": 200.5, "legsCm": [124.25, 163.75],
    }
    assert payload.get("width") is None
    assert "unitPriceCOP" not in payload["jobItemDraft"]
    assert not any("vendorSKU" in component
                   for component in payload["jobItemDraft"]["components"])

    nonce = uuid4().hex[:12]
    org = "synthetic-swift-v1-org-" + nonce
    monkeypatch.setattr(
        settings, "admin_api_key_hash",
        hashlib.sha256(ADMIN_KEY.encode()).hexdigest(),
    )
    await cleanup(org)
    try:
        async with AsyncClient(transport=ASGITransport(app=app),
                               base_url="http://test") as client:
            identity = dict(
                organizationID=org, organizationName="Synthetic Swift Company",
                userID="synthetic-user-"+nonce, displayName="Synthetic Estimator",
                email=nonce+"@example.invalid", membershipID="synthetic-seat-"+nonce,
                active=True, sharedCompanyAccess=True,
                allCustomers=True, allProjects=True,
                roles=[], customerIDs=[], projectIDs=[],
                capabilities=["sync", "item.create", "item.edit"],
                pilotSeatLimit=2, sessionID="synthetic-session-"+uuid4().hex,
                sessionTTLSeconds=3600,
            )
            auth = await client.post(
                "/internal/admin/v1/bootstrap",
                headers={"X-Vitrial-Admin-Key": ADMIN_KEY}, json=identity,
            )
            assert auth.status_code == 200, auth.text
            bearer = {"Authorization": "Bearer "+auth.json()["accessToken"]}
            async with SessionFactory() as db:
                db.add(CanonicalCustomer(organization_id=org,
                                         customer_id="synthetic-customer"))
                await db.flush()
                db.add(CanonicalProject(
                    organization_id=org, project_id="synthetic-project",
                    customer_id="synthetic-customer",
                ))
                await db.flush()
                db.add(CanonicalProjectSector(
                    organization_id=org, project_sector_id="synthetic-sector",
                    project_id="synthetic-project",
                    sector_id="sector-aluminum-glass-steel",
                ))
                await db.commit()
            sent = await client.post("/api/v1/sync/push", json=wire, headers=bearer)
            assert sent.status_code == 200, sent.text
            assert sent.json()["acceptedRecordIDs"] == [rec["id"]], sent.text
            assert sent.json()["rejectedRecordIDs"] == []
            repeated = await client.post("/api/v1/sync/push", json=wire, headers=bearer)
            assert repeated.status_code == 200
            assert repeated.json()["acceptedRecordIDs"] == [rec["id"]]
            response = await client.get("/api/v1/sync/pull?cursor=seq:0",
                                        headers=bearer)
            assert response.status_code == 200, response.text
            items = [r for r in response.json()["records"]
                     if r["entityType"] == "item" and r["entityID"] == "synthetic-item"]
            assert len(items) == 1
            pulled = json.loads(base64.b64decode(items[0]["payload"], validate=True))
            assert pulled["jobItemDraft"] == payload["jobItemDraft"]
            assert pulled.get("width") is None
            assert items[0]["serverRevision"] > 0
            # Actual base64 Swift wire is retried with four malicious,
            # independently identified edits; no altered server-side draft
            # or further revision is allowed into the event log.
            attempts = [
                ("approved-status", lambda d: d["jobItemDraft"].update(
                    templateReviewStatus="approved")),
                ("missing-leg", lambda d: d["jobItemDraft"]["opening"].update(
                    legsCm=[124.25])),
                ("flattened-width", lambda d: d.update(width={
                    "value": 124.25, "unit": "cm"
                })),
                ("mismatched-project", lambda d: d["jobItemDraft"].update(
                    projectID="synthetic-other-project")),
            ]
            for name, modify in attempts:
                forged_item = copy.deepcopy(payload)
                modify(forged_item)
                forged = copy.deepcopy(wire)
                forged_rec = forged["records"][0]
                forged_rec["id"] = rec["id"]+"-"+name
                forged_rec["clientMutationID"] = forged_rec["id"]
                forged_rec["baseServerRevision"] = items[0]["serverRevision"]
                forged_rec["payload"] = base64.b64encode(
                    json.dumps(forged_item).encode("utf-8")
                ).decode("ascii")
                denied = await client.post("/api/v1/sync/push",
                                           json=forged, headers=bearer)
                assert denied.status_code == 200, denied.text
                assert denied.json()["rejectedRecordIDs"] == [forged_rec["id"]]
                assert denied.json()["acceptedRecordIDs"] == []
            async with SessionFactory() as db:
                saved = await db.get(SyncEntity, (org, "item", "synthetic-item"))
                assert saved is not None
                assert saved.payload_json["jobItemDraft"]["opening"]["legsCm"] == [
                    124.25, 163.75
                ]
                assert saved.server_revision == items[0]["serverRevision"]
            assert (await client.get("/api/v1/sync/pull")).status_code == 401
    finally:
        await cleanup(org)
